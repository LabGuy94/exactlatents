"""Harvest a release corpus by streaming Python files and extracting functions.

This stage harvests, extracts, filters, deduplicates, and excludes evaluation
examples. The annotation, draw, and materialization stages shape its output.

Design points:
- Every function row carries a byte span into its stored parent file, so
  file-tier and project-tier datasets remain queries over the same artifact.
- Qualified names (``path.py::Class.method``) prevent name collisions.
- Decorators are included in the extracted function source.
- Evaluation exclusion fails closed over canary, OOD, and post-cut references.
- Functions must contain 16–4096 encoder tokens.
- Each repository contributes at most 150 functions.
- Progress and seen hashes are persisted after every shard.

Run:  uv run python dataset/corpus_build.py --source starcoder \
        --target 3200000 --out data/corpus_v2
Smoke: --source githubcode --target 500 --out out/corpus_smoke
"""
import argparse
import ast
import hashlib
import json
import pickle
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

ROOT = Path(__file__).resolve().parent.parent

p = argparse.ArgumentParser()
p.add_argument("--source", choices=["starcoder", "githubcode", "localdir", "stackv3"], default="starcoder")
p.add_argument("--min-file-ts", type=str, default=None,
               help="stackv3: keep only files modified on/after this date (YYYY-MM-DD)")
p.add_argument("--dir", type=str, default=None, help="localdir source: directory of .py files "
               "(filenames repo__owner__path.py style or plain; smoke/testing path)")
p.add_argument("--target", type=int, default=3_200_000, help="function rows to harvest")
p.add_argument("--out", type=str, default="data/corpus_v2")
p.add_argument("--repo-cap", type=int, default=150)
p.add_argument("--min-tok", type=int, default=16)
p.add_argument("--max-tok", type=int, default=4096)
p.add_argument("--shard-rows", type=int, default=50_000)
p.add_argument("--skip-files", type=int, default=0, help="stream fast-forward (resume)")
p.add_argument("--band", action="append", default=None, metavar="LO:HI:COUNT",
               help="band-targeted harvest (repeatable): keep a function ONLY if its "
                    "n_tokens falls in [LO,HI] (inclusive) of a band whose COUNT is not "
                    "yet met; stop when ALL band targets are met (--target ignored). "
                    "Default off = original behavior.")
args = p.parse_args()

# [lo, hi, target, got] per requested band (default None = original behavior)
bands = None
if args.band:
    bands = []
    for spec in args.band:
        lo, hi, cnt = (int(x) for x in spec.split(":"))
        assert lo <= hi and cnt > 0, f"bad --band {spec}"
        bands.append([lo, hi, cnt, 0])

from datasets import load_dataset
from transformers import AutoTokenizer

tok = AutoTokenizer.from_pretrained("Qwen/Qwen3-1.7B")

SOURCES = {
    "starcoder": dict(path="bigcode/starcoderdata", data_dir="python",
                      f_content="content", f_repo="max_stars_repo_name",
                      f_path="max_stars_repo_path", f_license=None),
    "githubcode": dict(path="codeparrot/github-code", name="Python-all",
                       f_content="code", f_repo="repo_name", f_path="path",
                       f_license="license"),
}
PERMISSIVE = {"mit", "apache-2.0", "bsd-3-clause", "bsd-2-clause", "isc",
              "unlicense", "cc0-1.0", "0bsd"}

# --- eval exclusion (fail closed) --------------------------------------------
excl_hashes, excl_repos = set(), set()
for f in ("canaries.jsonl", "canaries_v2.jsonl", "canaries_ood.jsonl", "canaries_smoke.jsonl"):
    for l in open(ROOT / "data" / f):
        excl_hashes.add(hashlib.md5(json.loads(l)["code"].strip().encode()).hexdigest())
for l in open(ROOT / "data/postcut_corpus/functions.jsonl"):
    r = json.loads(l)
    excl_hashes.add(hashlib.md5(r["code"].strip().encode()).hexdigest())
    excl_repos.add(r["repo"].lower())
for l in open(ROOT / "data/postcut_corpus/manifest.jsonl"):
    excl_repos.add(json.loads(l)["repo"].lower())
assert len(excl_hashes) > 25_000 and len(excl_repos) > 200, \
    f"eval exclusion refs look wrong ({len(excl_hashes)} hashes, {len(excl_repos)} repos) — refusing to build"
print(f"exclusion: {len(excl_hashes)} eval hashes, {len(excl_repos)} eval repos")

GENERATED_MARKERS = ("do not edit", "auto-generated", "autogenerated",
                     "generated by", "this file was generated")


def style_features(node, code, src_seg):
    doc = ast.get_docstring(node)
    n_str = sum(1 for x in ast.walk(node)
                if isinstance(x, ast.Constant) and isinstance(x.value, str))
    return {
        "is_async": isinstance(node, ast.AsyncFunctionDef),
        "decorated": bool(node.decorator_list),
        "has_docstring": doc is not None,
        "typed": bool(node.returns) or any(a.annotation for a in node.args.args),
        "string_share": round(sum(len(x.value) for x in ast.walk(node)
                                  if isinstance(x, ast.Constant) and isinstance(x.value, str)
                                  ) / max(len(src_seg), 1), 3),
        "n_strings": n_str,
    }


def extract(content):
    """yield (qualified_suffix, code_with_decorators, byte_span, features, is_method)"""
    # Match ast's universal-newline behavior when computing byte offsets.
    content = content.replace("\r\n", "\n").replace("\r", "\n")
    try:
        tree = ast.parse(content)
    except (SyntaxError, ValueError, RecursionError, MemoryError):
        return
    b = content.encode()
    lines = content.split("\n")
    starts = [0]
    for ln in lines:
        starts.append(starts[-1] + len(ln.encode()) + 1)

    def seg(node):
        first = node.decorator_list[0] if node.decorator_list else node
        a = starts[first.lineno - 1] + first.col_offset
        # decorators start at '@', col_offset points at the expression
        if node.decorator_list:
            a = starts[first.lineno - 1] + b[starts[first.lineno - 1]:a].rfind(b"@")
            if a < starts[first.lineno - 1]:
                a = starts[first.lineno - 1]
        z = starts[node.end_lineno - 1] + node.end_col_offset
        return a, z

    def walk(nodes, prefix, in_class):
        for node in nodes:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                a, z = seg(node)
                code = b[a:z].decode(errors="replace").strip()
                name = f"{prefix}{node.name}" if prefix else node.name
                yield name, code, (a, z), node, in_class
                # nested defs: rarely useful as standalone units; skip descent
            elif isinstance(node, ast.ClassDef):
                yield from walk(node.body, f"{node.name}.", True)

    yield from walk(tree.body, "", False)


if args.source == "stackv3":
    # The Stack v3 (crawl-end 2025-08-07): rows are REPOS with a files[] array.
    # Flatten to file-rows; keep permissive Python, drop PII-redacted files
    # (inline <NAME>/<EMAIL>/<KEY>/<PASSWORD> placeholders — not original bytes).
    src = dict(f_content="content", f_repo="repo", f_path="path", f_license=None)
    import calendar
    import time as _time
    _min_ts = 0
    if args.min_file_ts:
        _min_ts = calendar.timegm(_time.strptime(args.min_file_ts, "%Y-%m-%d"))
    _PII = ("<NAME>", "<EMAIL>", "<PASSWORD>", "<KEY>")

    def _sv3_rows():
        sv3 = load_dataset("HuggingFaceCode/stack-v3-train", split="train",
                           streaming=True).shuffle(seed=7, buffer_size=1)
        if args.skip_files:
            sv3 = sv3.skip(args.skip_files)
        for rep in sv3:
            repo = rep.get("repo_path") or "unknown"
            meta = rep.get("github_metadata") or {}
            for f in rep.get("files") or []:
                if f.get("language") != "Python":
                    continue
                if f.get("license_type") != "permissive":
                    continue
                ts = f.get("file_timestamp") or 0
                if ts and _min_ts and ts < _min_ts:
                    continue
                c = f.get("content") or ""
                if any(m in c for m in _PII):
                    continue
                yield {"content": c, "repo": repo, "path": f.get("file_path"),
                       "_prov": {"commit_id": rep.get("commit_id"),
                                 "file_ts": ts,
                                 "repo_created": meta.get("repo_created_at")}}
    ds = _sv3_rows()
elif args.source == "localdir":
    src = dict(f_content="content", f_repo="repo", f_path="path", f_license=None)

    def _local_rows():
        for fp in sorted(Path(args.dir).rglob("*.py")):
            parts = fp.stem.split("__")
            repo = "/".join(parts[:2]) if len(parts) >= 3 else f"local/{fp.parent.name}"
            yield {"content": fp.read_text(errors="replace"), "repo": repo,
                   "path": "__".join(parts[2:]) + ".py" if len(parts) >= 3 else str(fp)}
    ds = _local_rows()
else:
    src = SOURCES[args.source]
    kw = dict(split="train", streaming=True)
    if "data_dir" in src:
        kw["data_dir"] = src["data_dir"]
    if "name" in src:
        kw["name"] = src["name"]
    ds = load_dataset(src["path"], **kw)
    if args.skip_files:
        ds = ds.skip(args.skip_files)

out = ROOT / args.out
(out / "files").mkdir(parents=True, exist_ok=True)
(out / "functions").mkdir(parents=True, exist_ok=True)
state_p = out / "state.pkl"
if state_p.exists():
    st = pickle.load(open(state_p, "rb"))
    seen, repo_count, n_fn, n_file, shard_i, files_seen = (
        st["seen"], st["repo_count"], st["n_fn"], st["n_file"], st["shard_i"], st["files_seen"])
    if bands and st.get("band_got"):
        for bd, got in zip(bands, st["band_got"]):
            bd[3] = got
    print(f"resumed: {n_fn} fns, {files_seen} files seen (pass --skip-files {files_seen})")
else:
    seen, repo_count = set(), {}
    n_fn = n_file = shard_i = files_seen = 0

fn_buf, file_buf = [], []
t0 = time.time()
hb = open(out / "heartbeat", "w")

def flush():
    global shard_i, fn_buf, file_buf
    if fn_buf:
        with open(out / "functions" / f"shard_{shard_i:04d}.jsonl", "w") as f:
            for r in fn_buf:
                f.write(json.dumps(r) + "\n")
    if file_buf:
        import pandas as pd
        pd.DataFrame(file_buf).to_parquet(out / "files" / f"shard_{shard_i:04d}.parquet")
    shard_i += 1
    fn_buf, file_buf = [], []
    st_d = {"seen": seen, "repo_count": repo_count, "n_fn": n_fn,
            "n_file": n_file, "shard_i": shard_i, "files_seen": files_seen}
    if bands:
        st_d["band_got"] = [bd[3] for bd in bands]
    pickle.dump(st_d, open(state_p, "wb"))


def targets_met():
    if bands:
        return all(bd[3] >= bd[2] for bd in bands)
    return n_fn >= args.target


def band_status():
    return " ".join(f"{bd[3]}/{bd[2]}@{bd[0]}-{bd[1]}" for bd in bands)

for row in ds:
    files_seen += 1
    if targets_met():
        break
    if bands and files_seen % 250_000 == 0:
        msg = (f"[{time.strftime('%H:%M:%S')}] streaming: seen {files_seen} "
               f"bands {band_status()}")
        print(msg, flush=True)
        hb.seek(0); hb.write(msg + "\n"); hb.truncate(); hb.flush()
    content = row[src["f_content"]].replace("\r\n", "\n").replace("\r", "\n")
    repo = (row[src["f_repo"]] or "unknown").lower()
    if src["f_license"] and (row[src["f_license"]] or "").lower() not in PERMISSIVE:
        continue
    if repo in excl_repos or repo_count.get(repo, 0) >= args.repo_cap:
        continue
    if not (200 < len(content) < 500_000):
        continue
    head = content[:400].lower()
    file_is_generated = any(m in head for m in GENERATED_MARKERS)

    kept_any = False
    try:
        fns = list(extract(content))
    except Exception:
        continue  # one pathological file must never kill a 12h stream
    for name, code, span, node, is_method in fns:
        if repo_count.get(repo, 0) >= args.repo_cap:
            break
        h = hashlib.md5(code.strip().encode()).hexdigest()
        if h in seen or h in excl_hashes:
            continue
        n_tok = len(tok(code, add_special_tokens=False).input_ids)
        if not (args.min_tok <= n_tok <= args.max_tok):
            continue
        if n_tok > 2048 and file_is_generated:
            continue  # long-tail generated-code guard
        bi = None
        if bands:
            bi = next((i for i, bd in enumerate(bands)
                       if bd[0] <= n_tok <= bd[1] and bd[3] < bd[2]), None)
            if bi is None:
                continue  # outside every unmet band
        seen.add(h)
        feats = style_features(node, content, code)
        fn_buf.append({"repo": repo, "path": row[src["f_path"]],
                       "qualified": f"{row[src['f_path']]}::{name}",
                       "func_name": name, "code": code, "n_tokens": n_tok,
                       "span": list(span), "is_method": is_method,
                       "source": args.source, **row.get("_prov", {}), **feats})
        repo_count[repo] = repo_count.get(repo, 0) + 1
        n_fn += 1
        if bi is not None:
            bands[bi][3] += 1
        kept_any = True
    if kept_any:
        file_buf.append({"repo": repo, "path": row[src["f_path"]],
                         "content": content, "source": args.source})
        n_file += 1
    if bands and targets_met():
        break  # don't block on fetching one more row just to notice we're done
    if len(fn_buf) >= args.shard_rows:
        flush()
        rate = n_fn / max(time.time() - t0, 1)
        remaining = (sum(max(bd[2] - bd[3], 0) for bd in bands) if bands
                     else args.target - n_fn)
        eta_h = remaining / max(rate, 1) / 3600
        tgt = f"bands {band_status()}" if bands else f"fns {n_fn}/{args.target}"
        msg = (f"[{time.strftime('%H:%M:%S')}] {tgt} files {n_file} "
               f"repos {len(repo_count)} seen {files_seen} rate {rate:.0f}/s eta {eta_h:.1f}h")
        print(msg, flush=True)
        hb.seek(0); hb.write(msg + "\n"); hb.truncate(); hb.flush()

flush()
print(f"done: {n_fn} functions from {n_file} files across {len(repo_count)} repos "
      f"in {(time.time()-t0)/3600:.2f}h -> {out}"
      + (f" | bands {band_status()} seen {files_seen}" if bands else ""))
